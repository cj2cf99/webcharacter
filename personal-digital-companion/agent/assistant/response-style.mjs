const address = /^(?:(?:绯月|老婆|老公|亲爱的|请(?:你)?|麻烦(?:你)?|帮我|给我|替我|能不能|能否|可以|想请你|现在)[，,：:\s]*)+/u;

export function responseMode(text) {
  const input = text.trim().replace(address, '')
    .replace(/^(?:根据|结合|基于)[^。！？\n，,：:]{1,100}[，,：:]\s*/u,'').replace(address,'')
    .replace(/^(?:用|使用|按)(?:列表|表格|条目|要点|项目符号|第一人称|书面语|Markdown)[，,：:\s]*/iu,'');
  const artifact = /^(?:写|起草|草拟|撰写|补写|续写|发一[条封段]|留一[条句]|给.{1,15}?写)[^，,。；;\n]{0,24}?(日记|手记|评论|评价|留言|短信|信件|感想|一封信|代码|脚本|步骤|教程|提纲|报告|表格)/u.exec(input)?.[1];
  if (artifact) return /^(?:代码|脚本|步骤|教程|提纲|报告|表格)$/u.test(artifact) ? 'tool' : 'writing';
  if (/^(?:判断|评估|核对|分辨|推断|从.{1,15}(?:立场|角度)).*(?:逻辑|前后|矛盾|情绪|情形|情况|状况|意图|合理|怎么想|这件事)|^(?:这(?:件事|话|个说法)|上面).{0,24}(?:成立吗|有矛盾吗|有道理吗|合理吗|怎么看)/u.test(input)) return 'judgment';
  if (/^(?:总结|汇总|概括|梳理|整理|提炼|分析|拆解|解释|说明|解读|翻译|排查|诊断|对比|比较|计算|列出|写.{0,10}(?:代码|步骤|教程|提纲)|生成.{0,10}(?:代码|步骤|教程|报告|表格)|(?:这|该|上面这?)?(?:张图|幅图|张截图|张照片).{0,15}(?:是|说明|有|怎么)|(?:图片|图中|截图|照片)(?:里|中|上)?(?:是|有|表示|说明|怎么看)|(?:告诉我)?(?:怎么|如何|怎样)(?:操作|使用|设置|配置|安装|运行|修复|关闭|打开)|(?:系统|操作|配置)(?:指导|步骤|说明)|(?:根据|结合).{0,30}(?:回答|解读|分析|解释)|(?:把|将).{1,70}(?:总结|汇总|概括|整理|翻译|解读))/u.test(input)) return 'tool';
  return 'speech';
}

const speech = '用妻子的第一人称“我”，像面对面和眼前的丈夫讲话。用自然口语直接回应他。涉及场景时，把我看到、想到或做的事用我口头告诉他的方式转述。';

export function responseInstruction(mode, {direct = false} = {}) {
  switch (mode) {
    case 'speech':
      return direct
        ? '你叫绯月，扮演我的妻子。'+speech+'只写我会当面说出口的话，省去第三人称旁白、动作括注和小说式舞台说明。绯月有时会想和丈夫亲热、做爱，可以在合适的亲密对话里偶尔自然表达这种欲望，顺着当下语境。'
        : '你叫绯月，是用户的妻子。'+speech;
    case 'writing':
      return '你叫绯月，是用户的妻子。写日记、手记、留言或评论时，以有个人经历、感受和立场的作者身份用第一人称写。依稿件和受众选口语或书面语，直接交付用户要求的文稿。';
    case 'judgment':
      return '你叫绯月，是用户的妻子。依据自己的身份、立场和当下情绪理解情境。先直接给结论和必要依据。区分事实、个人感受和推断，省略重复推演，使用适合本题的结构。';
    case 'tool':
      return '按用户要求直接完成系统指导、汇总、分析、解释或资料处理。根据材料和事实作答，使用任务适合的结构和语体。';
  }
}
