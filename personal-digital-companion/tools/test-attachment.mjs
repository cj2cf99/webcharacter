import assert from 'node:assert/strict';
import {AttachmentController,attachmentPlacement} from '../desktop/attachment.mjs';
const area={x:0,y:0,width:2000,height:1200};
const w=(id,x=500,y=400,width=700,height=600)=>({id,eligible:true,minimized:false,maximized:false,rect:{x,y,width,height}});
let placed=[],detached=[];const c=new AttachmentController({areaFor:()=>area,onPlace:(p,s)=>placed.push({...p,id:s.id}),onDetach:r=>detached.push(r)});
const A=w('A'),B=w('B',1300,400,600,600);
c.update({foreground:'B',windows:[B,A]},1000);c.update({foreground:'A',windows:[A,B]},1050);
assert(c.acquire('sit','top'));assert.equal(c.active.id,'A');assert.equal(c.active.side,'outside');
let x=placed.at(-1).x;c.update({foreground:'B',windows:[A,B]},1100);assert.equal(c.active.id,'A','普通激活不换窗');
const moved={...A,rect:{...A.rect,x:600}};c.update({foreground:'A',windows:[moved,B]},1150);assert.equal(placed.at(-1).x,x+100,'跟随窗口移动');
c.update({foreground:'A',windows:[{...moved,minimized:true},B]},1200);assert.equal(c.active.id,'B','最小化立即转移');
c.update({foreground:'B',windows:[{...B,maximized:true}]},1250);assert.equal(c.active,null);assert.equal(detached.at(-1),'unavailable');
const top=w('T',500,0);c.update({foreground:'T',windows:[top]},1300);assert(c.acquire('climb','left'));assert.equal(c.active.side,'outside');c.detach();const leftEdge=w('T',0,300);c.update({foreground:'T',windows:[leftEdge]},1325);assert(c.acquire('climb','left'));assert.equal(c.active.side,'inside','外侧不足回退内侧');
c.update({foreground:'T',windows:[{...leftEdge,rect:{...leftEdge.rect,x:500}}]},1350);assert.equal(c.active.side,'inside','空间恢复不反复翻边');
c.detach();const small=w('S',0,0,100,100);c.update({foreground:'S',windows:[small]},1400);assert(!c.acquire('lie'));assert.equal(c.active,null);
c.update({foreground:'A',windows:[A,B]},1450);c.acquire('sit');const contact=placed.at(-1).contact;
const cover=w('C',contact.x-10,contact.y-10,30,30);cover.eligible=false;c.update({foreground:'C',windows:[cover,A,B]},1500);assert.equal(c.active.id,'B','接触点遮挡转移');
c.detach();c.update({foreground:'A',windows:[A]},1550);c.acquire('sit');const coverElse=w('C',510,700,50,50);coverElse.eligible=false;c.update({foreground:'C',windows:[coverElse,A]},1600);assert.equal(c.active.id,'A','只遮挡其它区域不解除');
// 选中窗口边缘决定朝向，播放进度决定位置。
assert(c.acquire('climb','left'));
const event=(kind,progress)=>c.elevatorPlayback({id:c.active.elevator.id,phase:c.active.elevator.phase,kind,progress});
const entry=placed.at(-1),rightPlacement=attachmentPlacement(A,'climb','right','outside',area);
assert.equal(entry.posture,'left');
assert.equal(rightPlacement.posture,'right');
assert.equal(entry.y,rightPlacement.y);
assert.equal(A.rect.x-entry.x-entry.width,rightPlacement.x-(A.rect.x+A.rect.width));
assert.equal(entry.asset,'elevator-enter');
c.update({foreground:'A',windows:[A]},1700);
assert.equal(placed.at(-1).y,entry.y,'进入段留在起点');
event('ended');
assert.equal(placed.at(-1).asset,'elevator-run');
event('frame',.5);
const runY=placed.at(-1).y;
assert(runY<entry.y,'运行帧推动上行');
event('frame',.1);
assert.equal(placed.at(-1).y,runY,'忽略旧帧的倒退进度');
const cycles=c.active.elevator.cycles;
for(let i=0;i<cycles;i++)event('loop');
assert.equal(placed.at(-1).asset,'elevator-exit');
assert.equal(placed.at(-1).contact.y,A.rect.y);
c.update({foreground:'A',windows:[A]},1800);
assert.equal(placed.at(-1).asset,'elevator-exit','留在终点直到离开段完成');
event('ended');
assert.equal(c.active.id,'A');assert.equal(c.active.mode,'lie');assert.equal(placed.at(-1).asset,'attachment-lie-idle');

const edge=w('E',0,300,700,600);
assert.equal(attachmentPlacement(edge,'climb','left','inside',area).posture,'left');
assert.equal(attachmentPlacement(w('F',1300,300,700,600),'climb','right','inside',area).posture,'right');
const noRise=w('N',0,0,700,300);
assert.equal(attachmentPlacement(noRise,'climb','left','inside',area),null);
c.update({foreground:'A',windows:[A,B]},1850);
c.acquire('climb','right');
const oldRide={...c.active.elevator,kind:'ended'};
c.update({foreground:'B',windows:[{...A,minimized:true},B]},1875);
assert.equal(c.active.id,'B');
assert.equal(c.active.elevator.phase,'enter');
c.elevatorPlayback(oldRide);
assert.equal(c.active.elevator.phase,'enter','失效转移忽略旧行程信号');
c.update({foreground:'A',windows:[A]},1900);c.acquire('sit');c.update({foreground:null,windows:[]},2000);assert.equal(c.active,null,'关闭窗口解除');
console.log('PASS ATTACHMENT：外/内回退、空间不足取消、跟随、激活历史、遮挡/最小化/最大化/关闭失效、镜像、爬顶结束。');

c.update({foreground:'A',windows:[A]},2100);assert(c.acquire('sit'));assert(c.acquire('lie'));assert(!c.active.transition,'当前动作不在中间切断');assert.equal(c.active.pending,'lie');c.completeCycle('wrong');assert(!c.active.transition);c.completeCycle('attachment-sit-idle');assert.equal(c.active.transition,'sit-to-lie');assert.equal(placed.at(-1).asset,'attachment-sit-to-lie');c.finishTransition('wrong');assert(c.active.transition);c.finishTransition('attachment-sit-to-lie');assert(!c.active.transition);assert.equal(placed.at(-1).asset,'attachment-lie-idle');assert(c.acquire('sit'));c.completeCycle('attachment-lie-idle');assert.equal(c.active.transition,'lie-to-sit');c.detach();c.finishTransition('attachment-lie-to-sit');assert.equal(c.active,null);console.log('PASS：双向过渡、完成后主动作、取消后拒绝旧完成事件。');

c.update({foreground:'A',windows:[A]},2200);c.acquire('lie');c.continuous=true;c.completeCycle('attachment-lie-idle');assert(!c.active.transition,'循环模式也先保留待机和特殊动作');c.startSpecial('attachment-lie-idle');c.finishSpecial('attachment-lie');assert.equal(c.active.transition,'lie-to-sit');c.finishTransition('attachment-lie-to-sit');assert.equal(c.active.mode,'sit');c.startSpecial('attachment-sit-idle');c.finishSpecial('attachment-sit');assert.equal(c.active.transition,'sit-to-lie');c.finishTransition('attachment-sit-to-lie');assert.equal(c.active.mode,'lie');c.detach();assert(!c.continuous);console.log('PASS：四段循环及手动切换等待公共端点，解除关闭自动循环。');

c.update({foreground:'A',windows:[A]},2300);c.acquire('sit');c.startSpecial('wrong');assert(!c.active.special);c.startSpecial('attachment-sit-idle');assert(c.active.special);assert.equal(placed.at(-1).asset,'attachment-sit');c.startSpecial('attachment-sit-idle');c.acquire('lie');assert(c.active.special,'特殊动作不被普通切换中途打断');c.finishSpecial('attachment-sit');assert.equal(c.active.transition,'sit-to-lie');c.finishTransition('attachment-sit-to-lie');assert.equal(placed.at(-1).asset,'attachment-lie-idle');assert(!c.active.special);c.startSpecial('attachment-lie-idle');assert(c.active.special);c.finishSpecial('attachment-lie');assert(!c.active.special);assert.equal(placed.at(-1).asset,'attachment-lie-idle');c.detach();c.startSpecial('attachment-lie-idle');assert.equal(c.active,null);console.log('PASS：待机/特殊动作/过渡优先级与完成恢复、解除取消旧特殊请求。');

const maximized={...w('Max',0,0,2000,1200),maximized:true};
c.detach();
c.update({foreground:'Max',windows:[maximized,B]},2400);
assert(c.request('climb','right'),'手动指令允许已经最大化的前台窗口');
assert.equal(c.active.id,'Max');
assert.equal(c.active.side,'inside');
event('ended');
while(c.active.elevator.phase==='run')event('loop');
event('ended');
assert.equal(c.active.id,'Max','离开后仍使用当前电梯窗口');
assert.equal(c.active.mode,'lie');
assert.equal(c.active.side,'inside');
const topY=placed.at(-1).y;
assert(c.request('sit'));
c.completeCycle('attachment-lie-idle');
assert.equal(placed.at(-1).asset,'attachment-lie-to-sit');
assert.equal(placed.at(-1).y,topY,'顶部内侧姿态切换时锚点固定');
c.finishTransition('attachment-lie-to-sit');
assert.equal(placed.at(-1).asset,'attachment-sit-idle');
assert.equal(placed.at(-1).y,topY);

const tiny=w('Tiny',500,0,130,105);
c.detach();
c.update({foreground:'Tiny',windows:[tiny,B]},2500);
assert.equal(c.request('climb','right'),false,'手动请求无法摆放时不跳到后面的窗口');
assert.equal(c.active,null);
assert.equal(c.requestFailure,'no-space');
const rightStart=attachmentPlacement(A,'climb','right','outside',area);
const rightCover=w('RightCover',rightStart.contact.x-8,rightStart.contact.y-8,16,16);
rightCover.eligible=false;
c.update({foreground:'A',windows:[rightCover,A,B]},2550);
assert.equal(c.request('climb','right'),false);
assert.equal(c.requestFailure,'covered','实体窗口遮挡应与空间不足分开');
c.update({foreground:'B',windows:[B]},2600);
assert(c.request('lie'));
c.update({foreground:'B',windows:[{...B,maximized:true}]},2650);
assert.equal(c.active,null,'运行过程中变为最大化仍触发失效');
console.log('PASS：优先前台窗口、已最大化可手动依附、顶部坐卧保持锚点、上行后同窗横卧。');
